/*
 * Geographic correlation-search builder.
 *
 * Generates SPL for "alert when ≥N events of TYPE within RADIUS km
 * within TIME min" — the most common geographic correlation pattern.
 *
 * Example output (for N=3, radius=50, window=5min, auth_failure):
 *
 *   index=auth action=failure earliest=-5m
 *   | geostats latfield=lat longfield=lng zl=7 count
 *   | where count >= 3
 *
 * Or, for "events near a fixed point":
 *
 *   index=auth action=failure earliest=-5m
 *   | eval _dist_m = 6371000 * acos(
 *       cos(pi()/180 * 37.7749) * cos(pi()/180 * lat) *
 *       cos(pi()/180 * lng - pi()/180 * -122.4194) +
 *       sin(pi()/180 * 37.7749) * sin(pi()/180 * lat))
 *   | where _dist_m <= 50000
 *   | stats count
 *   | where count >= 3
 *
 * Also emits a complete `savedsearches.conf` alert stanza so the user
 * can copy-paste it directly into their app.
 *
 * BM-CT-1: stateless module.
 */

/**
 * Build SPL for a "near-point" correlation.
 *
 * @param {object} opts
 *   indexFilter: string      e.g. 'index=auth action=failure'
 *   centerLat: number
 *   centerLng: number
 *   radiusKm: number
 *   minEvents: number
 *   windowMin: number
 */
export function nearPointSPL(opts) {
    const o = opts || {};
    const filter = o.indexFilter || 'index=*';
    const radiusM = (o.radiusKm || 50) * 1000;
    const win = o.windowMin || 5;
    const minEv = o.minEvents || 3;
    const lat = o.centerLat;
    const lng = o.centerLng;
    return ''
        + filter + ' earliest=-' + win + 'm\n'
        + '| eval _dist_m = 6371000 * acos(\n'
        + '    cos(pi()/180 * ' + lat + ') * cos(pi()/180 * lat) *\n'
        + '    cos(pi()/180 * lng - pi()/180 * ' + lng + ') +\n'
        + '    sin(pi()/180 * ' + lat + ') * sin(pi()/180 * lat))\n'
        + '| where _dist_m <= ' + radiusM + '\n'
        + '| stats count AS event_count\n'
        + '| where event_count >= ' + minEv;
}

/**
 * Build SPL for a "spatial cluster" correlation using geostats.
 *
 * @param {object} opts
 *   indexFilter: string
 *   minEvents: number
 *   windowMin: number
 *   hexResolution: number (1-12)
 */
export function clusterSPL(opts) {
    const o = opts || {};
    const filter = o.indexFilter || 'index=*';
    const win = o.windowMin || 5;
    const minEv = o.minEvents || 3;
    const zl = o.hexResolution || 7;
    return ''
        + filter + ' earliest=-' + win + 'm\n'
        + '| geostats latfield=lat longfield=lng zl=' + zl + ' count\n'
        + '| where count >= ' + minEv
        + '\n';
}

/**
 * Build the full savedsearches.conf alert stanza wrapping the SPL.
 *
 * Conforms to the canonical pattern in
 * .cursor/rules/splunk-alerts.mdc — uses enableSched / counttype /
 * relation / quantity (NOT the banned legacy keys).
 */
export function alertStanza(opts) {
    const o = opts || {};
    const name = o.name || 'better_map geo correlation alert';
    const description = o.description || 'Geographic correlation alert generated by Better Map';
    const cron = o.cron || '*/5 * * * *';
    const earliestExpr = o.earliest || '-5m';
    const severity = o.severity || 4;
    const search = String(o.search || '')
        .split(/\r?\n/)
        .map(function (l, i, arr) { return i < arr.length - 1 ? l + ' \\' : l; })
        .join('\n');
    return ''
        + '[' + name + ']\n'
        + 'description = ' + description + '\n'
        + 'search = ' + search + '\n'
        + 'cron_schedule = ' + cron + '\n'
        + 'dispatch.earliest_time = ' + earliestExpr + '\n'
        + 'dispatch.latest_time = now\n'
        + 'enableSched = 1\n'
        + 'disabled = 0\n'
        + 'counttype = number of events\n'
        + 'relation = greater than\n'
        + 'quantity = 0\n'
        + 'alert.severity = ' + severity + '\n'
        + 'alert.digest_mode = 1\n'
        + 'alert.suppress = 1\n'
        + 'alert.suppress.period = 30m\n'
        + 'alert.track = 1\n';
}
